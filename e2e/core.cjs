const { chromium } = require('playwright');
const out = process.argv[2] || require('node:os').tmpdir();
const URL = process.argv[3] || 'http://localhost:5173/';
let fails = 0;
const log = (ok, msg) => { if (!ok) fails++; console.log((ok ? 'PASS ' : 'FAIL ') + msg); };
(async () => {
  const browser = await chromium.launch();
  for (const [width, height] of [[430, 932], [375, 667]]) {
    const ctx = await browser.newContext({ viewport: { width, height }, deviceScaleFactor: 1, hasTouch: true, isMobile: true });
    const page = await ctx.newPage();
    const errors = [];
    page.on('pageerror', (e) => errors.push(e.message));
    page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
    const shot = async (name) => {
      await page.waitForTimeout(350);
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
      log(overflow <= 0, `${width}px ${name}: no horizontal scroll (overflow ${overflow})`);
      await page.screenshot({ path: `${out}/${width}-${name}.png`, fullPage: true });
    };
    const head = (label) => page.locator('.row-head', { hasText: label });
    const open = async (label) => { if ((await head(label).getAttribute('aria-expanded')) !== 'true') await head(label).click(); };
    const pick = (label) => page.getByLabel(label, { exact: true }).click();
    const submit = () => page.getByRole('button', { name: 'מצא לי מתנות מתאימות' }).click();

    await page.goto(URL);
    await page.evaluate(() => document.fonts.ready);
    await page.waitForTimeout(600);
    const catalog = (await page.evaluate(() => fetch('/api/bootstrap').then((r) => r.json()))).catalog;
    await shot('home');
    await page.getByRole('button', { name: 'תפריט' }).click();
    log(await page.getByRole('dialog').getByRole('link', { name: 'שאלון התאמת מתנה' }).isVisible(), `${width}px menu opens`);
    await shot('menu');
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'יום הולדת' }).click();
    await page.waitForURL(/#search/);
    log((await head('סוג האירוע').locator('.row-value').innerText()) === 'יום הולדת', `${width}px shortcut fills occasion`);
    await shot('search');
    await open('קרבה למקבל המתנה'); await pick('חברה');
    log((await head('גיל מקבל המתנה').getAttribute('aria-expanded')) === 'true', `${width}px answering moves to the next question`);
    await shot('search-ages');
    await open('תחומי עניין'); await pick('טיפוח');
    await open('תקציב');
    await page.getByLabel('מינימום (₪)').fill('300'); await page.getByLabel('מקסימום (₪)').fill('100');
    await submit();
    log(await page.getByRole('alert').isVisible() && page.url().includes('#search'), `${width}px reversed budget shows error`);
    log(await page.getByLabel('מינימום (₪)').inputValue() === '300', `${width}px reversed budget keeps values`);
    await page.getByLabel('מינימום (₪)').fill('100'); await page.getByLabel('מקסימום (₪)').fill('300');
    await open('מיקום'); await pick('איסוף עצמי'); await pick('תל אביב');
    await shot('search-filled');
    const cta = await page.getByRole('button', { name: 'מצא לי מתנות מתאימות' }).boundingBox();
    log(cta && cta.y + cta.height <= height, `${width}px submit stays within the viewport`);
    await submit();
    await page.waitForURL(/#results/);
    await page.locator('.result-list').waitFor();
    const names = await page.locator('.result-list .gift-name').allInnerTexts();
    const shown = names.map((n) => catalog.find((g) => g.name === n));
    log(shown.length > 0 && shown.every((g) => g && g.price >= 100 && g.price <= 300), `${width}px results respect the budget: ${shown.map((g) => g && g.price).join(', ')}`);
    log(shown.every((g) => g.interests.includes('care') && g.occasions.includes('birthday') && g.stores.some((s) => s.regions.includes('telAviv'))), `${width}px results match interest, occasion and region`);
    log((await page.locator('h1').innerText()) === 'מתנות מתאימות ליום הולדת של חברה', `${width}px results heading`);
    await shot('results');
    const gift = shown[0];
    await page.getByRole('button', { name: `שמירת ${gift.name} במועדפים` }).click();
    log(await page.getByText('נשמר במועדפים').isVisible(), `${width}px save shows feedback`);
    await page.getByRole('link', { name: 'עריכת החיפוש' }).click();
    await page.waitForURL(/#search/);
    await open('תקציב');
    log(await page.getByLabel('מקסימום (₪)').inputValue() === '300' && (await head('מיקום').innerText()).includes('תל אביב'), `${width}px edit keeps values`);
    await page.goBack();
    await page.locator('a.gift-link', { hasText: gift.name }).click();
    await page.waitForURL(new RegExp('#gift-' + gift.id));
    await page.locator('.why').waitFor();
    const why = await page.locator('.why').innerText();
    log(['טיפוח', 'יום הולדת', 'חברה', 'תל אביב'].every((w) => why.includes(w)), `${width}px details explain matched choices`);
    log(await page.getByRole('button', { name: `הסרת ${gift.name} מהמועדפים` }).isVisible(), `${width}px heart state shared with details`);
    const buy = await page.getByRole('button', { name: 'איפה ניתן לרכוש?' }).boundingBox();
    const nav = await page.locator('.bottom-nav').boundingBox();
    log(buy.y + buy.height <= nav.y, `${width}px purchase button clear of the bottom bar`);
    await shot('details');
    await page.getByRole('button', { name: 'איפה ניתן לרכוש?' }).click();
    await page.waitForURL(new RegExp('#stores-' + gift.id));
    await page.locator('.store').first().waitFor();
    const link = page.getByRole('link', { name: 'מעבר לעמוד המוצר בחנות' });
    log((await link.getAttribute('href')) === gift.stores[0].url && (await page.locator('main').innerText()).includes('תל אביב'), `${width}px stores screen links to the real product page`);
    await shot('stores');
    await page.getByRole('button', { name: 'חזרה' }).click();
    await page.waitForURL(new RegExp('#gift-' + gift.id));
    await page.getByRole('navigation', { name: 'ניווט ראשי' }).getByRole('link', { name: 'המתנות שאהבתי' }).click();
    await page.getByRole('heading', { name: 'המתנות שאהבתי' }).waitFor();
    log((await page.locator('.grid').innerText()).includes(gift.name), `${width}px favourite listed`);
    await page.reload();
    log((await page.locator('.grid').innerText()).includes(gift.name), `${width}px favourite survives refresh`);
    const six = catalog.slice(0, 6).map((g) => g.id);
    await page.evaluate((ids) => localStorage.setItem('giftfit:favorites', JSON.stringify(ids)), six);
    await page.reload();
    await shot('favorites');
    for (const id of six) await page.locator('.gift-card', { has: page.locator(`a[href="#gift-${id}"]`) }).getByRole('button').click();
    log(await page.getByText('כאן יופיעו המתנות שסימנת בלב').isVisible(), `${width}px empty favourites message`);
    await page.goto(URL + '#search'); await page.reload();
    await page.getByRole('button', { name: 'ניקוי הבחירות' }).click();
    await submit(); await page.locator('.result-list').waitFor();
    log((await page.locator('.result-list li').count()) === 2, `${width}px two results first`);
    await page.getByRole('button', { name: 'להמלצות נוספות' }).click();
    log((await page.locator('.result-list li').count()) === 5, `${width}px more shows up to five`);
    await page.goto(URL + '#search'); await page.reload(); await open('תקציב');
    await page.getByLabel('מינימום (₪)').fill('5000'); await page.getByLabel('מקסימום (₪)').fill('6000');
    await submit();
    log(await page.getByRole('button', { name: 'עריכת החיפוש' }).waitFor({ timeout: 5000 }).then(() => true, () => false), `${width}px no-match offers edit`);
    log(errors.length === 0, `${width}px no console errors ${errors.join(' | ')}`);
    await ctx.close();
  }
  await browser.close();
  console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
})().catch((e) => { console.error('ERROR', e.message.split('\n').slice(0, 8).join('\n')); process.exit(1); });
